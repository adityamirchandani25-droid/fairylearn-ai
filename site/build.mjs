// build.mjs — builds the marketing site into public/ with no dependencies.
//
//   node site/build.mjs        (or: npm run build:site)
//
// What it does:
//   1. Joins site/styles/*.css (in filename order) into public/assets/site.css.
//   2. Joins site/scripts/*.js (in filename order) into public/assets/site.js.
//   3. Copies site/scripts/modules/*.mjs (page-only browser modules) to public/assets/js/.
//   4. Imports every module in site/pages/, wraps each page in the shared layout and writes
//      it to public/ (e.g. /lessons → public/lessons.html).
//   5. Writes public/site-files.json: the URL → file map server.mjs uses to serve these files
//      locally. On Vercel, public/ is served directly with cleanUrls.
// The generated files are committed, so deploys need no build step.
import { readdir, readFile, writeFile, mkdir, copyFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { document } from './lib/layout.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const site = join(root, 'site');
const out = process.env.SITE_OUT || join(root, 'public');
const assets = join(out, 'assets');

const sorted = async (dir, ext) => existsSync(dir) ? (await readdir(dir)).filter(f => f.endsWith(ext)).sort() : [];
const write = async (file, content) => { await mkdir(dirname(file), { recursive: true }); await writeFile(file, content); };

async function concat(dir, ext, banner) {
  const files = await sorted(dir, ext);
  const parts = await Promise.all(files.map(async f => `/* ── ${f} ── */\n${await readFile(join(dir, f), 'utf8')}`));
  return `${banner}\n${parts.join('\n')}`;
}

async function walk(dir) {
  if (!existsSync(dir)) return [];
  const entries = await readdir(dir, { withFileTypes: true });
  const nested = await Promise.all(entries.map(entry => entry.isDirectory() ? walk(join(dir, entry.name)) : [join(dir, entry.name)]));
  return nested.flat();
}

export async function build() {
  const banner = '/* Generated by site/build.mjs — edit the sources in site/, not this file. */';
  await write(join(assets, 'site.css'), await concat(join(site, 'styles'), '.css', banner));
  await write(join(assets, 'site.js'), await concat(join(site, 'scripts'), '.js', banner));

  await rm(join(assets, 'js'), { recursive: true, force: true });
  for (const f of await sorted(join(site, 'scripts', 'modules'), '.mjs')) {
    await mkdir(join(assets, 'js'), { recursive: true });
    await copyFile(join(site, 'scripts', 'modules', f), join(assets, 'js', f));
  }
  if (existsSync(join(site, 'favicon.svg'))) await copyFile(join(site, 'favicon.svg'), join(assets, 'favicon.svg'));

  const routes = {};
  for (const f of await sorted(join(site, 'pages'), '.mjs')) {
    const mod = await import(pathToFileURL(join(site, 'pages', f)).href);
    const result = await mod.default();
    for (const page of [result].flat()) {
      if (!page?.path || !page?.file) throw new Error(`${f}: a page needs path and file`);
      if (routes[page.path]) throw new Error(`${f}: duplicate route ${page.path}`);
      await write(join(out, page.file), document(page));
      routes[page.path] = page.file;
    }
  }

  // Static assets the local server may send (fonts, images, css, js).
  for (const file of await walk(assets)) {
    const rel = relative(out, file).split('\\').join('/');
    routes[`/${rel}`] = rel;
  }
  const manifest = Object.fromEntries(Object.entries(routes).sort(([a], [b]) => a.localeCompare(b)));
  await write(join(out, 'site-files.json'), `${JSON.stringify(manifest, null, 2)}\n`);
  return manifest;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const manifest = await build();
  const pages = Object.keys(manifest).filter(p => !p.startsWith('/assets/'));
  console.log(`Built ${pages.length} pages: ${pages.join(', ')}`);
}
